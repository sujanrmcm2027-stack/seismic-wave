import type { MultiSourceEventGroup, RawSourceObservation } from "@/data/multiSourceSchema";
import { generateMultiSourceAssessment } from "./assessmentEngine";

function createObservation(
  source: "NEMRC" | "CENC" | "USGS",
  eventId: string,
  mag: number,
  magType: string,
  lat: number,
  lng: number,
  depthKm: number,
  originIso: string,
  place: string,
  url: string,
  status: "REVIEWED" = "REVIEWED",
  revisions: any[] = [],
): RawSourceObservation {
  const timeMs = new Date(originIso).getTime();
  return {
    observationId: `${source.toLowerCase()}_${eventId}`,
    source,
    sourceEventId: eventId,
    magnitudeValue: mag,
    magnitudeType: magType,
    latitude: lat,
    longitude: lng,
    depthKm,
    originTimeUtc: originIso,
    originTimeMs: timeMs,
    placeName: place,
    status,
    retrievedAt: "2026-09-29T12:00:00Z",
    publishedAt: originIso,
    updatedAt: originIso,
    sourceUrl: url,
    rawPayload: { benchmark: true, source, eventId },
    revisions,
  };
}

